#!/usr/bin/env bash
#
# qvenc 장치를 QEMU 소스 트리에 통합한다.
#
#   hw/qvenc.c            -> $QEMU_SRC/hw/misc/qvenc.c
#   include/qvenc_regs.h  -> $QEMU_SRC/include/hw/misc/qvenc_regs.h
#   hw/misc/meson.build   에 qvenc.c 빌드 규칙 추가
#   hw/misc/Kconfig       에 config QVENC 추가
#
# 여러 번 실행해도 안전하다 (idempotent). 소스가 바뀌면 복사본만 갱신된다.

source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

[ -d "$QEMU_SRC" ] || die "QEMU 소스가 없다: $QEMU_SRC  (먼저 scripts/build_qemu.sh 실행)"
[ -f "$QEMU_SRC/hw/misc/meson.build" ] || die "QEMU 트리처럼 보이지 않는다: $QEMU_SRC"

say "장치 소스 복사"
install -D -m 0644 "$QVENC_ROOT/hw/qvenc.c"           "$QEMU_SRC/hw/misc/qvenc.c"
install -D -m 0644 "$QVENC_ROOT/include/qvenc_regs.h" "$QEMU_SRC/include/hw/misc/qvenc_regs.h"

# 마커 사이를 통째로 갈아끼운다. 그래야 내용이 바뀌어도 (예: depends 추가)
# 두 번째 실행에서 옛 블록이 남지 않는다.
BEGIN_MARK="# BEGIN qvenc (generated by scripts/apply_qemu.sh)"
END_MARK="# END qvenc"

patch_block() {
    local file="$1" body="$2"
    if grep -qF "$BEGIN_MARK" "$file"; then
        sed -i "/^$(printf '%s' "$BEGIN_MARK" | sed 's/[][\.*^$\/]/\\&/g')\$/,/^$END_MARK\$/d" "$file"
    fi
    {
        printf '%s\n' "$BEGIN_MARK"
        printf '%s\n' "$body"
        printf '%s\n' "$END_MARK"
    } >> "$file"
}

say "meson.build: qvenc.c 빌드 규칙"
patch_block "$QEMU_SRC/hw/misc/meson.build" \
    "system_ss.add(when: 'CONFIG_QVENC', if_true: files('qvenc.c'))"

# MSI_NONBROKEN: msi_init() 를 쓰는 장치는 edu.c 와 마찬가지로 이 의존이 필요하다.
say "Kconfig: config QVENC"
patch_block "$QEMU_SRC/hw/misc/Kconfig" \
"config QVENC
    bool
    default y if TEST_DEVICES
    depends on PCI && MSI_NONBROKEN"

say "완료. 이제 QEMU 를 (재)빌드하면 -device qvenc 를 쓸 수 있다."
